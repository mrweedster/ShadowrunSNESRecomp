#!/usr/bin/env python3
"""embed_rom.py — bake the guest image into the executable (stage-1 C0 / M3).

Writes one translation unit holding the exact ROM bytes, plus a CMake fragment
next to it so the build can pass the matching macros to the framework host:

    snesrecomp_embedded_rom[]        the image, bare (no SMC copier header)
    SNESRECOMP_EMBEDDED_ROM_SIZE     length of that array
    SNESRECOMP_EMBEDDED_ROM_NAME     what it was called, for diagnostics

Those three names are the contract with the desktop host
(snesrecomp/runner/src/desktop/host_main.c, SNESRECOMP_EMBEDDED_ROM); the host
declares the array with the size, so a definition with a different count does
not link, and it re-hashes the image against this project's digests before
boot. Both checks exist so image and machine code can never be from different
revisions: a build like that behaves badly in ways that look like a game bug.

The image and the digests are never duplicated here. The image is found by the
same search tools/regen.sh uses (--rom, SNESRECOMP_ROM, a known filename at the
repo root, rom.cfg) and the digests come from rom_identity.txt through the
framework's parser. An image that is not the one this build was generated from
stops the configure.

    python3 tools/embed_rom.py --out build-embed/embedded_rom.c [--rom ROM]
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import subprocess
import sys
import zlib

# Same names regen.sh tries, same order.
ROM_NAMES = ("Shadowrun (USA).sfc", "shadowrun.sfc", "shadowrun.smc")

# A copier header is 512 bytes and the digests in rom_identity.txt are of the
# bare image, so both spellings are candidates and the digests decide.
SMC_HEADER_SIZE = 512

TEMPLATE = '''/* Generated by tools/embed_rom.py -- do not edit, do not commit.
 *
 *   source   : {source}
 *   bytes    : {size}
 *   crc32    : {crc32}
 *   sha256   : {sha256}
 *
 * Built only for a ROM-free target: the macros come from the CMake option
 * SHADOWRUN_EMBED_ROM, and the host declares this array with the same length,
 * so an image that disagrees with that length cannot link. */

#include <stddef.h>

#if !defined(SNESRECOMP_EMBEDDED_ROM_SIZE)
#error "embedded_rom.c needs SNESRECOMP_EMBEDDED_ROM_SIZE (see CMakeLists.txt)"
#endif

const unsigned char {symbol}[{size}] = {{
{body}
}};

_Static_assert(sizeof({symbol}) == (size_t)SNESRECOMP_EMBEDDED_ROM_SIZE,
               "SNESRECOMP_EMBEDDED_ROM_SIZE disagrees with the embedded image");
_Static_assert(sizeof({symbol}) == {size},
               "the embedded image is not {size} bytes");
'''


def fail(msg: str) -> "NoReturn":  # type: ignore[name-defined]
    print(f"embed_rom.py: {msg}", file=sys.stderr)
    raise SystemExit(1)


def framework_root(args: argparse.Namespace, script_dir: pathlib.Path) -> pathlib.Path:
    import os
    for candidate in (os.environ.get("SNESRECOMP_ROOT", ""),
                      str(script_dir.parent / "snesrecomp")):
        if candidate and (pathlib.Path(candidate) / "snesrecomp_cli.py").is_file():
            return pathlib.Path(candidate)
    fail("no framework checkout: pass --framework-root or set SNESRECOMP_ROOT")


def run_python(py: str, script: pathlib.Path, argv: list[str]) -> str:
    if not script.is_file():
        fail(f"{script} missing — run: git submodule update --init --recursive")
    proc = subprocess.run([py, str(script), *argv], capture_output=True, text=True)
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        fail(f"{script.name} {' '.join(argv)} failed: {detail}")
    return proc.stdout


def identity_of(root: pathlib.Path, identity_file: pathlib.Path) -> dict[str, str]:
    """rom_identity.txt, read by the framework's parser — not a second copy."""
    out: dict[str, str] = {}
    parser = root / "tools" / "rom_identity.py"
    for field in ("rom_file", "rom_size", "expected_crc32", "expected_sha256"):
        out[field] = run_python(sys.executable, parser,
                                [str(identity_file), "--get", field]).strip()
    return out


def resolve_image(args: argparse.Namespace, root: pathlib.Path,
                  project_root: pathlib.Path,
                  prefer: str = "") -> pathlib.Path:
    if args.rom:
        path = pathlib.Path(args.rom)
        if not path.is_file():
            fail(f"--rom {path} is not a file")
        return path
    cli = root / "snesrecomp_cli.py"
    argv = ["resolve-rom", "--project-root", str(project_root)]
    # The edition's own filename first: an embedded German build must not pick
    # up the USA image that happens to sit at the repo root.
    names = ((prefer,) if prefer else ()) + ROM_NAMES
    for name in names:
        argv += ["--name", name]
    return pathlib.Path(run_python(sys.executable, cli, argv).strip())


def main() -> int:
    script_dir = pathlib.Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, type=pathlib.Path,
                    help="C file to write (a matching .cmake fragment goes beside it)")
    ap.add_argument("--rom", help="image to embed; default is regen.sh's search")
    ap.add_argument("--identity", type=pathlib.Path,
                    default=script_dir.parent / "rom_identity.txt")
    ap.add_argument("--framework-root", default="",
                    help="snesrecomp checkout (default: SNESRECOMP_ROOT or ./snesrecomp)")
    ap.add_argument("--symbol", default="snesrecomp_embedded_rom",
                    help="C array name (the host declares this one extern)")
    ap.add_argument("--name", default="",
                    help="label compiled into the binary; default rom_identity.txt's rom_file")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    root = pathlib.Path(args.framework_root) if args.framework_root \
        else framework_root(args, script_dir)
    project_root = script_dir.parent

    ident = identity_of(root, args.identity)
    if not ident["expected_crc32"] and not ident["expected_sha256"]:
        fail(f"{args.identity}: no digests, so an embedded image could not be "
             "checked against this build's machine code. Refusing to bake one in.")

    image = resolve_image(args, root, project_root, ident.get("rom_file", ""))
    data = image.read_bytes()

    # The digests decide which spelling is the guest image, so a copier header
    # is stripped only when that is provably the same ROM.
    candidates = [(data, 0)]
    if len(data) > SMC_HEADER_SIZE:
        candidates.append((data[SMC_HEADER_SIZE:], SMC_HEADER_SIZE))

    chosen = None
    for blob, offset in candidates:
        crc = f"{zlib.crc32(blob) & 0xFFFFFFFF:08x}"
        sha = hashlib.sha256(blob).hexdigest()
        if ident["expected_crc32"] and crc != ident["expected_crc32"]:
            continue
        if ident["expected_sha256"] and sha != ident["expected_sha256"]:
            continue
        chosen = (blob, offset, crc, sha)
        break
    if chosen is None:
        first = candidates[0][0]
        fail(f"{image} is not the ROM this build was generated from:\n"
             f"    crc32   {zlib.crc32(first) & 0xFFFFFFFF:08x}"
             f" (want {ident['expected_crc32']})\n"
             f"    sha256  {hashlib.sha256(first).hexdigest()}\n"
             f"    want    {ident['expected_sha256']}")
    blob, offset, crc, sha = chosen
    if offset and not args.quiet:
        print(f"embed_rom.py: stripped a {offset}-byte copier header from {image}")

    want_size = int(ident["rom_size"] or 0)
    if want_size and len(blob) != want_size:
        fail(f"{image}: {len(blob)} bytes, {args.identity} says {want_size}")

    name = args.name or ident["rom_file"] or image.name

    body = "\n".join(
        "  " + " ".join(f"0x{b:02x}," for b in blob[i:i + 16])
        for i in range(0, len(blob), 16))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(TEMPLATE.format(source=image, size=len(blob), crc32=crc,
                                        sha256=sha, symbol=args.symbol, body=body),
                        encoding="utf-8", newline="\n")

    # CMake cannot re-parse rom_identity.txt without duplicating its parser, so
    # the values it needs for the host's macros are written back out here.
    fragment = args.out.with_suffix(".cmake")
    fragment.write_text(
        "# Generated by tools/embed_rom.py -- do not edit.\n"
        f'set(EMBED_ROM_PATH  "{image}")\n'
        f'set(EMBED_ROM_NAME  "{name}")\n'
        f"set(EMBED_ROM_SIZE  {len(blob)})\n",
        encoding="utf-8", newline="\n")

    if not args.quiet:
        print(f"embed_rom.py: {image.name} — {len(blob)} bytes, crc32 {crc} — "
              f"-> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
