#!/usr/bin/env python3
"""Generate the edition table the universal Shadowrun executable links.

The ROM digests stay in rom_identity*.txt. This tool turns the identity files
for the editions a build carries into one C translation unit:

    shadowrun_editions_data.c

It is run by CMake at configure time, so changing a digest (or adding an
edition to SHADOWRUN_EDITIONS) re-runs it and the binary cannot drift from the
files tools/regen.sh verifies against.

The per-edition facts that are not in the identity file -- the program-module
id, the hand-cursor WRAM words, and the save root -- live here, next to the
comment explaining them. They are port measurements, not ROM metadata.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

# The generated tree's module id and symbol prefix are fixed by CMake:
#   USA       src/gen      unprefixed, module id "main"
#   Germany   src/gen-de   --module-prefix shadowrun_de --module-id shadowrun-de
#   Sweden    src/gen-sv   --module-prefix shadowrun_sv --module-id shadowrun-sv
#
# Cursor words are measured in evidence/language_roms.md: the translations'
# inserted text moved the same WRAM block 0x1C lower.
EDITIONS = {
    "us": {
        "module_id": "main",
        "cursor": (0x01F0, 0x01F2, 0x01F4),
        "save_root": "saves",
    },
    "de": {
        "module_id": "shadowrun-de",
        "cursor": (0x01D4, 0x01D6, 0x01D8),
        "save_root": "saves/de",
    },
    "sv": {
        "module_id": "shadowrun-sv",
        "cursor": (0x01D4, 0x01D6, 0x01D8),
        "save_root": "saves/sv",
    },
}

REQUIRED_KEYS = (
    "display_name",
    "rom_file",
    "expected_sha256",
    "expected_sha1",
    "expected_crc32",
)

_LINE = re.compile(r"^([A-Za-z0-9_]+)[ \t]*=[ \t]*(.*)$")


def parse_identity(path: pathlib.Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _LINE.match(line)
        if not match:
            continue
        key, value = match.group(1).lower(), match.group(2).strip()
        if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
            value = value[1:-1]
        values[key] = value

    missing = [key for key in REQUIRED_KEYS if not values.get(key)]
    if missing:
        raise ValueError(f"{path}: missing {', '.join(missing)}")
    return values


def cstr(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(editions: list[tuple[str, dict[str, str]]], stock: str) -> str:
    tags = [tag for tag, _ in editions]
    if stock not in tags:
        raise ValueError(f"--stock {stock!r} is not one of {', '.join(tags)}")
    stock_index = tags.index(stock)

    out = [
        "/* Auto-generated by tools/gen_editions.py. Do NOT hand-edit.",
        " *",
        " * The editions this build carries, read from their rom_identity*.txt",
        " * files. Re-run CMake after editing an identity file or changing",
        " * SHADOWRUN_EDITIONS.",
        " */",
        '#include "edition.h"',
        '#include "rom_identity.h"',
        "",
        "const ShadowrunEditionDef kShadowrunEditionDefs[] = {",
    ]

    for tag, ident in editions:
        meta = EDITIONS[tag]
        cursor_x, cursor_y, cursor_gate = meta["cursor"]
        out.extend(
            [
                "    {",
                f"        .tag = {cstr(tag)},",
                f"        .module_id = {cstr(meta['module_id'])},",
                f"        .display_name = {cstr(ident['display_name'])},",
                f"        .rom_file = {cstr(ident['rom_file'])},",
                f"        .expected_sha256 = {cstr(ident['expected_sha256'])},",
                f"        .expected_sha1 = {cstr(ident['expected_sha1'])},",
                f"        .expected_crc32 = {cstr(ident['expected_crc32'])},",
                f"        .cursor_x = 0x{cursor_x:04X}u,",
                f"        .cursor_y = 0x{cursor_y:04X}u,",
                f"        .cursor_gate = 0x{cursor_gate:04X}u,",
                f"        .save_root = {cstr(meta['save_root'])},",
                "    },",
            ]
        )

    out.extend(
        [
            "};",
            "const unsigned kShadowrunEditionDefCount =",
            "    (unsigned)(sizeof kShadowrunEditionDefs / sizeof kShadowrunEditionDefs[0]);",
            f"const unsigned kShadowrunStockEditionIndex = {stock_index}u;",
            "",
            "const SnesRomRevision kShadowrunRomRevisions[] = {",
        ]
    )
    for tag, ident in editions:
        out.append(
            "    { .label = %s, .sha256_hex = %s, .sha1_hex = %s, "
            ".crc32_hex = %s, .note = NULL },"
            % (
                cstr(ident["display_name"]),
                cstr(ident["expected_sha256"]),
                cstr(ident["expected_sha1"]),
                cstr(ident["expected_crc32"]),
            )
        )
    out.extend(
        [
            "};",
            "const int kShadowrunRomRevisionCount =",
            "    (int)(sizeof kShadowrunRomRevisions / sizeof kShadowrunRomRevisions[0]);",
            "",
            "const char *const kShadowrunKnownSha1Hex[] = {",
        ]
    )
    for _tag, ident in editions:
        out.append(f"    {cstr(ident['expected_sha1'])},")
    out.extend(
        [
            "};",
            "const int kShadowrunKnownSha1Count =",
            "    (int)(sizeof kShadowrunKnownSha1Hex / sizeof kShadowrunKnownSha1Hex[0]);",
            "",
        ]
    )
    return "\n".join(out)


def write_if_changed(path: pathlib.Path, text: str) -> bool:
    old = path.read_text(encoding="utf-8") if path.is_file() else None
    if old == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8", newline="\n")
    temporary.replace(path)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--edition",
        action="append",
        default=[],
        metavar="TAG=IDENTITY",
        required=True,
        help="an edition and its rom_identity*.txt (repeatable)",
    )
    parser.add_argument(
        "--stock",
        required=True,
        help="tag of the unprefixed stock module (the first edition listed)",
    )
    parser.add_argument("--out", required=True, help="C file to write")
    args = parser.parse_args()

    editions: list[tuple[str, dict[str, str]]] = []
    seen: set[str] = set()
    for spec in args.edition:
        tag, separator, name = spec.partition("=")
        if not separator or not tag or not name:
            parser.error(f"--edition wants TAG=IDENTITY, got {spec!r}")
        if tag not in EDITIONS:
            parser.error(f"unknown edition {tag!r}; use {', '.join(EDITIONS)}")
        if tag in seen:
            parser.error(f"edition {tag!r} listed twice")
        seen.add(tag)
        path = pathlib.Path(name)
        if not path.is_file():
            parser.error(f"identity file not found: {path}")
        try:
            editions.append((tag, parse_identity(path)))
        except (OSError, ValueError) as exc:
            parser.error(str(exc))

    try:
        text = render(editions, args.stock)
    except ValueError as exc:
        parser.error(str(exc))

    out = pathlib.Path(args.out)
    changed = write_if_changed(out, text)
    print(f"editions: {', '.join(tag for tag, _ in editions)} "
          f"(stock {args.stock}) -> {out}{' (updated)' if changed else ''}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
