#!/usr/bin/env bash
# Per-seed attribution for a gap-seed round: build one variant per seed, and
# answer two questions about each one -- what the route did, and whether the
# guest state still matches the control tree's.
#
#   SNESRECOMP_ROOT=/path/to/pin ./tests/seed_sweep.sh r4base \
#       80C399 80AAB3 80ABBC 80B1DB ...
#
# $1 is the control variant built by tests/seed_variant.sh (its executable is
# the reference the parity leg runs against); the rest are entry PCs from
# tests/gap_seeds.py's ranking, bare 6 hex digits.
#
# Why the parity leg: tests/seed_variant.sh already shows the cycle share
# change, and a scripted route says whether the run still reaches its gates.
# Neither says whether the compiled bodies compute the same machine state.  A
# seed that moves a third of the residue into AOT and quietly changes WRAM from
# frame N is not a win, and only a dump-vs-dump run against the control tree
# can tell those apart.  tests/parity.sh does exactly that: same route, same
# SRAM seed, frame dumps compared.
#
# Writes tests/out/r4/variant_s<pc>.out and tests/out/r4/parity_s<pc>.log, and
# one summary line per seed.  Nothing here edits the entry table by hand: each
# variant's seed table is generated by tests/gap_seeds.py inside seed_variant.sh.
set -uo pipefail
cd "$(cd "$(dirname "$0")/.." && pwd)"
base="${1:-}"; shift || true
[ -x "build-$base/ShadowrunSNESRecomp" ] || { echo "no control tree build-$base" >&2; exit 2; }
[ -n "${SNESRECOMP_ROOT:-}" ] || { echo "SNESRECOMP_ROOT must point at the pinned framework" >&2; exit 2; }
probe="${PROBE:-tests/out/probe_dense.txt}"
route="${ROUTE:-tests/scripts/combat.txt}"
out="tests/out/r4"
mkdir -p "$out"
rows=()
for pc in "$@"; do
  name="s$pc"
  ROUTE="$route" ./tests/seed_variant.sh "$name" --only "\$$pc" >"$out/variant_$name.out" 2>&1
  rc=$?
  ROUTE="$route" PORT_BIN="build-$base/ShadowrunSNESRecomp" \
    PORT_BIN2="build-$name/ShadowrunSNESRecomp" \
    ./tests/parity.sh "$probe" >"$out/parity_$name.log" 2>&1
  state=$(grep -oE 'identical over [0-9]+ frames|[0-9]+ of [0-9]+ frames differ|first divergence at frame_[0-9]+' \
          "$out/parity_$name.log" | tr '\n' ';')
  share=$(grep -oE 'aot +[0-9.]+%' "$out/variant_$name.out" | tail -1)
  exit_=$(grep -oE 'exit=[0-9]+ .*' "$out/variant_$name.out" | tail -1)
  aban=$(grep -oE '\[unresolved-abandon\] first hit site=\$[0-9A-F]+ frame=[0-9]+' \
         "$out/variant_$name.out" | tail -1)
  printf '%s\tseed $%s\tbuild rc=%s\t%s\t%s\t%s\tstate: %s\n' \
    "$name" "$pc" "$rc" "$exit_" "$aban" "$share" "$state" | tee -a "$out/sweep_$base.tsv"
done
